// Cleans residual mojibake (e.g. â‚¹) to proper Rupee symbol ₹
export function cleanRupee(str) {
  if (!str || typeof str !== 'string') return str;
  return str
    .replace(/â‚¹/g, '₹')
    .replace(/â\x80\x9a\xc2\xb9/g, '₹')
    .replace(/\u00e2\u201a\u00b9/g, '₹')
    .replace(/â\u0082\u00b9/g, '₹')
    .replace(/â/g, '');
}

// Returns fully localized scheme matching the user's selected language
export function getLocalizedScheme(scheme, language) {
  if (!scheme) return scheme;
  const lang = language || 'en';
  let sid = (scheme.scheme_id || scheme.id || '').toLowerCase();
  if (sid === 'pmss' || sid === 'pmsy') {
    sid = 'pm_scholarship_warb';
  }
  const langData = schemeTranslations[lang]?.[sid] || schemeTranslations.en?.[sid];

  const name = langData?.name || cleanRupee(scheme.scheme_name || scheme.name);
  const ministry = langData?.ministry || cleanRupee(scheme.ministry);
  const description = langData?.description || cleanRupee(scheme.description || scheme.short_desc);
  const benefit = langData?.benefit || cleanRupee(scheme.benefit || scheme.benefit_summary);
  const docs = (langData?.documents_required && langData.documents_required.length > 0)
    ? langData.documents_required
    : (scheme.documents_required && scheme.documents_required.length > 0)
      ? scheme.documents_required
      : (schemeTranslations.en?.[sid]?.documents_required || []);

  const localizedCriteria = (scheme.criteria || []).map((c) => {
    const cid = c.criterion_id || c.id || '';
    const field = c.field || '';
    const locLabel =
      langData?.criteria_labels?.[cid] ||
      langData?.criteria_labels?.[field] ||
      schemeTranslations.en?.[sid]?.criteria_labels?.[cid] ||
      schemeTranslations.en?.[sid]?.criteria_labels?.[field] ||
      c.label;
    return {
      ...c,
      label: cleanRupee(locLabel),
    };
  });

  return {
    ...scheme,
    scheme_name: cleanRupee(name),
    name: cleanRupee(name),
    ministry: cleanRupee(ministry),
    description: cleanRupee(description),
    short_desc: cleanRupee(description),
    benefit: cleanRupee(benefit),
    benefit_summary: cleanRupee(benefit),
    documents_required: docs.map(cleanRupee),
    criteria: localizedCriteria,
  };
}
